const GLOSSARY_SRC = `### The 3/10/50 Filter
“3 years, 10 years, or 50 years from now, will the outcome of this decision really matter? Will I deeply regret this action (or inaction)?”

### Degree Arbitrage
Strategically exploiting the university infrastructure to extract massive, asymmetric market value to build your own career using minimum time, money, and cognitive load. Consists of 4 pillars.

### Academic Arbitrage
Optimizing your unit and curriculum choices to maximize the hard skills and proof of work the market pays for, not the grades the rubric rewards.

### Identity Arbitrage
Using who you are at university (a student, or a role like Head of PR) as a legitimate reason to reach decision-makers who would ignore you otherwise.

Use it while the reason lasts, because it shrinks at graduation and ends when the fresh-grad window closes.

### Resource Arbitrage
Using what your university gives you access to (money, facilities, software, clubs, events, speakers, the alumni network) for your own goals, at little or no extra cost.

### Brand Arbitrage
Borrowing the trust of your university’s name, or anything that carries it (a club, a title, an event), so people take you seriously before you have your own proof.

### Pascal’s Degree-Unit Selection Inversion
The mechanic under Academic Arbitrage where your degree selection (macro) runs Passion & Mission > Vocation > Profession, but your unit selection (micro) inverts to Profession → Vocation → Passion & Mission.

*Profession can be ignored under the degree selection (macro)
*Passion can be ignored under the unit selection (micro)

### Asymmetric ROI
An action where the potential upside massively outweighs the input cost (time, capital).

(In the university context) Getting massively more out of the university system than you put in.

### Career Moat
Your un-replicable advantage: The intersection of 3 variables neither AI nor another graduate can copy, Asymmetric Capability, Calibrated Judgment, and Relational Equity. A 4th element, Scalable Architecture, multiplies a moat that already exists but does not create one.

1. Asymmetric Capability: the polymathic synthesis of unrelated disciplines and ruthless critical thinking, applied to a high-value market gap.

2. Calibrated Judgment: the ability to choose the right problem and the right move under uncertainty, before the market confirms the answer.

3. Relational Equity: your deep human network, your personal brand, and the unquantifiable trust you hold with decision-makers.

4. Scalable Architecture (multiplier): the systems that decouple a moat's payout from your hourly presence.

In simple words:
1. Asymmetric Capability = can you do the rare thing
2. Calibrated Judgment = do you point it at the right thing
3. Relational Equity = do people trust you to do it
4. Scalable Architecture (multiplier) = does it work when you're not in the room

### Capital Burn Rate
The cost of one hour of your degree, calculated as total tuition divided by total contact hours (contact hours = the total number of hours you spend in direct instruction with your lecturers. For most students, it’s the sum of all lecture and tutorial hours). It is what drips away every time you sit in a lecture, whether you are learning anything or not.

### Active Semester Burn Rate
The cost of simply being enrolled, calculated as total tuition divided by a 40-hour week across the full semester. It does not include rent, food, or transport. The real number is worse.

### Hurdle Rate
The minimum return your degree must earn on any hour you put in. 

(1) Your Active Semester Burn Rate sets the floor for every hour of your 40-hour week

(2) Capital Burn Rate sets the floor for every lecture or tutorial hour

Any hour whose long-term benefit falls below its rate is a losing trade: drop it, delegate it, or automate it.

### Meta-Liquidity
The trust capital of a high-signal proof of work: a reputation that makes the market come to you instead of you chasing it. Built through newsletters, LinkedIn presence, domain-specific content, and any public track record that compounds credibility. 

In the AI era, when the information environment floods with generated noise, Meta-Liquidity becomes the scarcest career asset because human trust is the one thing AI cannot manufacture.

### Locked-Door Degrees
Fields where you cannot explore your way in during second year because they demand immediate, sequential prerequisites from Day 1  (e.g., medicine, law).

The lock-in is a dual-edged asset. It restricts your flexibility, but it also keeps AI out, because displacement in these fields requires regulatory change (new laws, new licensing structures), not just technical capability.

### Ground Truth
The verified, uncomfortable reality about a situation that institutions, universities, parents, or the market are not telling you directly. Not opinion, not doom, not motivation: the specific, data-backed fact that changes your decision if you see it.

Every Ground Truth pairs a hard number (DOSM 35.2%, WEF 92M displaced, RM89/hr) with a proprietary framework that tells you what to do about it.

### Importance Triage
A 3-dimension scoring system that prices any task before you touch it. 

The 3 dimensions are MECE: 
  1. Goal Alignment (does this move your current semester goal?)
  2. Timing (is this stage of your degree the right moment for this task?)
  3. Environment (given everything else on your plate right now, is this the moment to act?)
Most students get overwhelmed because they give every task the same weight. The Importance Triage assigns a weight to each task so your best hours go to the highest-leverage move, not the loudest deadline.

### Strategic Gratitude
It’s appreciating your time and attention enough to stop leaking them, and deliberately redirecting the saved energy into work that compounds.

The system runs in 3 steps: find the leak, cut what doesn't belong, route the surplus.

### Credential Decay
The measurable erosion of a degree's market value over time, driven by the gap between what the credential signals and what the labor market actually rewards.

### Cognitive Sovereignty
The retained ability to think, reason, and produce judgment without AI as a dependency. In simple terms, it is keeping enough of the core reasoning in your own head that you can catch AI when it is wrong.

### Oral Defense
A real‑time test of your reasoning. Your ability to explain, justify, and defend the choices behind your work when someone pushes on the second layer.

Not what you know → what you own
Not the output → the reasoning behind the output
Not the answer → the logic chain that produced the answer
Not memorization → judgment, weighting, and decision‑making

### The 4 Hidden Assets
The 4 separable assets bundled into every degree at a single price: Credential, Knowledge, Status, and Infrastructure. Each is extracted by exactly one pillar of Degree Arbitrage.

### Cognitive Debt Trap
3-stage cycle: Acceleration (AI speeds up output) then Substitution (AI replaces the thinking) then Debt Collection (the skill atrophies and you can no longer do it without AI).

### Proof of Work System
The practice of turning every skill you claim into public, inspectable output (a shipped project, a written analysis, a recorded decision) so an employer can verify what you can do without relying on your credential. It is the student's answer to Signal Collapse.

### Ladder Collapse
The disappearance of the entry-level rungs that used to turn a graduate into an experienced hire: fewer junior openings, slower campus hiring, and flat starting pay, as AI absorbs the tasks those roles existed to do. It is the market-side event; Foundation Debt is the gap it leaves in each graduate.

### Signal Collapse
The repricing event in which a credential (degree, certification, brand-name employer on a resume) loses its power to clear a hiring bar on its own, because AI has made it cheap for employers to directly verify and execute the deliverable the credential used to proxy for.

When an AI model can verify and execute a deliverable itself, the employer stops paying for a credential-as-signal and starts paying only for output. The credential still gets you into the room, but it no longer clears the bar on its own.

### AI Orchestrator
Someone who designs a system of tools and agents to hit an outcome, rather than someone who operates one tool well.

The person who routes rented, pre-built AI capability into a real workflow that produces a real outcome, rather than the person who builds the underlying model.

### Foundation Debt
The cumulative gap between the on-the-job repetitions a career has always required to build real competence, and the shrinking supply of entry-level roles that used to provide those repetitions for free, now that AI absorbs the low-stakes cognitive work (searching, drafting, checking, modelling) first.

It accrues whether or not you notice it, and no one sends you a statement. You either fund the reps yourself, on purpose, or carry the debt into your first real job interview.

### High vs Low Liquidity
How quickly an hour or a skill turns into something the market pays for. A high-liquidity skill has steady, active demand (the Unit Navigator's LinkedIn Liquidity test: 30 to 50 active, mid-to-high-paying roles posted for it in the last month). Low-liquidity busywork is effort the market no longer pays for, or already automates.

### Information Asymmetry
When one side of a deal knows more than the other, and the side that knows less makes worse decisions (borrowed from economics; George Akerlof, 1970). In the university game, the university holds the information and you hold the capital. You break the asymmetry by verifying Ground Truth before you enrol in a unit.`;

